const { contextBridge, ipcRenderer } = require('electron')

contextBridge.exposeInMainWorld('api', {
  getConfig: () => ipcRenderer.invoke('get-config'),
  saveConfig: (config) => ipcRenderer.invoke('save-config', config),
  savePickSettings: (settings) => ipcRenderer.invoke('save-pick-settings', settings),
  saveCountdown: (list) => ipcRenderer.invoke('save-countdown', list),
  checkForUpdate: () => ipcRenderer.invoke('check-for-update'),
  getMessages: () => ipcRenderer.invoke('get-messages'),
  saveMessages: (msgs) => ipcRenderer.invoke('save-messages', msgs),
  deleteMessage: (id) => ipcRenderer.invoke('delete-message', id),
  clearMessages: () => ipcRenderer.invoke('clear-messages'),
  showPopup: (msg) => ipcRenderer.send('show-popup', msg),
  closePopup: () => ipcRenderer.send('close-popup'),
  closeHistory: () => ipcRenderer.send('close-history'),
  closeSettings: () => ipcRenderer.send('close-settings'),
  closeWindow: () => window.close(),
  closePassword: () => ipcRenderer.send('close-password'),
  closeRandomPick: () => ipcRenderer.send('close-random-pick'),
  closeUpdate: () => ipcRenderer.send('close-update'),
  closeTimer: () => ipcRenderer.send('close-timer'),
  closeDraw: () => ipcRenderer.send('close-draw'),
  closeFloat: () => ipcRenderer.send('close-float'),
  minimizeTimer: () => ipcRenderer.send('minimize-timer'),
  minimizeRandomPick: () => ipcRenderer.send('minimize-random-pick'),
  minimizeHistory: () => ipcRenderer.send('minimize-history'),
  openUpdateUrl: (url) => ipcRenderer.send('open-update-url', url),
  installUpdate: () => ipcRenderer.invoke('install-update'),
  updateTray: (connected) => ipcRenderer.send('update-tray', connected),
  verifyPassword: (pwd) => ipcRenderer.invoke('verify-password', pwd),
  getPasswordHint: () => ipcRenderer.invoke('get-password-hint'),
  forceResetPassword: (code) => ipcRenderer.invoke('force-reset-password', code),
  changePassword: (oldPwd, newPwd, hint) => ipcRenderer.invoke('change-password', oldPwd, newPwd, hint),
  cancelPassword: () => ipcRenderer.send('cancel-password'),
  getAutoLaunch: () => ipcRenderer.invoke('get-auto-launch'),
  setAutoLaunch: (enabled) => ipcRenderer.invoke('set-auto-launch', enabled),
  getAppVersion: () => ipcRenderer.invoke('get-app-version'),
  importExcel: () => ipcRenderer.send('import-excel'),
  loadNameList: () => ipcRenderer.invoke('load-name-list'),
  saveNameList: (names) => ipcRenderer.invoke('save-name-list', names),
  clearNameList: () => ipcRenderer.invoke('clear-name-list'),
  openTimer: () => ipcRenderer.send('open-timer'),
  openDraw: () => ipcRenderer.send('open-draw'),
  openRandomPick: () => ipcRenderer.send('open-random-pick'),
  openExamTimer: () => ipcRenderer.send('open-exam-timer'),
  closeExamTimer: () => ipcRenderer.send('close-exam-timer'),
  minimizeExamTimer: () => ipcRenderer.send('minimize-exam-timer'),
  startPreventSleep: () => ipcRenderer.send('start-prevent-sleep'),
  stopPreventSleep: () => ipcRenderer.send('stop-prevent-sleep'),
  setFloatClickThrough: (enabled) => ipcRenderer.send('set-float-click-through', enabled),
  setDrawClickThrough: (enabled) => ipcRenderer.send('set-draw-click-through', enabled),
  onImportResult: (callback) => ipcRenderer.on('import-result', (e, data) => callback(data)),
  onNewMessage: (callback) => ipcRenderer.on('new-message', (e, msg) => callback(msg)),
  onUpdateInfo: (callback) => ipcRenderer.on('update-info', (e, info) => callback(info)),
  onConnectionStatus: (callback) => ipcRenderer.on('connection-status', (e, connected) => callback(connected)),
  onCountdownRefresh: (callback) => ipcRenderer.on('countdown-refresh', () => callback()),
  openSchedule: () => ipcRenderer.send('open-schedule'),
  loadSchedule: () => ipcRenderer.invoke('load-schedule'),
  saveSchedule: (data) => ipcRenderer.invoke('save-schedule', data),
  importScheduleExcel: () => ipcRenderer.send('import-schedule-excel'),
  downloadScheduleTemplate: () => ipcRenderer.send('download-schedule-template'),
  exportScheduleCheck: (data) => ipcRenderer.send('export-schedule-check', data),
  applyScheduleMode: (mode) => ipcRenderer.send('apply-schedule-mode', mode),
  onScheduleImportResult: (cb) => ipcRenderer.on('schedule-import-result', (e, d) => cb(d)),
  onScheduleTemplateSaved: (cb) => ipcRenderer.on('schedule-template-saved', (e, d) => cb(d)),
  onScheduleExportSaved: (cb) => ipcRenderer.on('schedule-export-saved', (e, d) => cb(d)),
  onScheduleRefresh: (cb) => ipcRenderer.on('schedule-refresh', () => cb())
})
